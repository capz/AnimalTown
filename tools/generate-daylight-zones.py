EPOCH = int(datetime(2000, 1, 1, tzinfo=timezone.utc).timestamp())
END = (int(datetime(2100, 1, 3, tzinfo=timezone.utc).timestamp()) - EPOCH) // 60


def zone_data(directory, name):
    with (directory / name).open('rb') as file:
        zone = ZoneInfo.from_file(file)

    def offset(minute):
        value = datetime.fromtimestamp(EPOCH + 60 * minute, timezone.utc).astimezone(zone)
        seconds = int(value.utcoffset().total_seconds())
        if seconds % 60:
            raise ValueError(f'{name} has an offset that is not a whole minute')
        return seconds // 60

    first = -2880  # Include the UTC days on either side of the console RTC range.
    offsets = [offset(first)]
    transitions = []
    previous = offsets[0]
    for minute in range(first + 360, END + 1, 360):
        current = offset(minute)
        if current == previous:
            continue
        low, high = minute - 360, minute
        while high - low > 1:
            mid = (low + high) // 2
            if offset(mid) == previous:
                low = mid
            else:
                high = mid
        if current not in offsets:
            offsets.append(current)
        if len(offsets) > 8:
            raise ValueError(f'{name} exceeds the three-bit offset index')
        transitions.append(high * 8 + offsets.index(current))
        previous = current
    return tuple(offsets), tuple(transitions)


def generate(directory, version):
    offsets, transitions, cities = [], [], []
    for region, city, lat, lon, name in CITIES:
        values, changes = zone_data(directory, name)
        if values not in offsets:
            offsets.append(values)
        if changes not in transitions:
            transitions.append(changes)
        zone = f'new DaylightZone(Offsets{offsets.index(values)}, Transitions{transitions.index(changes)})'
        cities.append(f'        new DaylightLocation({region}, "{city}", {lat}, {lon}, {zone}),')

    yield f'// Generated by tools/generate-daylight-zones.py from IANA tzdb {version}.'
    yield '// Transition data is public domain. Times are UTC minutes since 2000-01-01.'
    yield 'namespace AnimalTown;\n\npublic static partial class DaylightLocations\n{'
    for i, values in enumerate(offsets):
        yield f'    private static readonly short[] Offsets{i} = {{'+', '.join(map(str, values))+'};'
    for i, changes in enumerate(transitions):
        yield f'    private static readonly int[] Transitions{i} = {{'
        for at in range(0, len(changes), 10):
            yield '        '+', '.join(map(str, changes[at:at+10]))+','
        yield '    };'
    region_values = ', '.join(f'"{name}"' for name in REGIONS)
    yield f'    private static readonly string[] Regions = {{{region_values}}};'
    yield f'    public const int Count = {len(cities)};'
    yield '    private static readonly DaylightLocation[] Cities = {'
    yield from cities
    yield '    };\n}'


if __name__ == '__main__':
    parser = ArgumentParser(description=__doc__)
    parser.add_argument('tzdir', type=Path, help='Compiled IANA zoneinfo directory')
    parser.add_argument('version', help='Version of that IANA release')
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / 'shared/AnimalTown.Domain/DaylightLocations.Data.cs'
    output.write_text('\n'.join(generate(args.tzdir, args.version))+'\n', encoding='utf-8')
