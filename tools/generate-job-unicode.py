#!/usr/bin/env python3
"""Cook pinned Unicode 14 canonical/letter tables for the console's mail grader.

Run with CPython's Unicode 14 database (the pinned builder's Python). The game
does not depend on Python, ICU, reflection or desktop normalization at runtime.
Unicode data license: assets/definitions/jobs/UNICODE-LICENSE.txt.
"""
from pathlib import Path
import unicodedata as ud

VERSION='14.0.0'
ROOT=Path(__file__).resolve().parents[1]

def ranges(values):
    result=[]
    for cp in values:
        if result and result[-1]+1==cp:result[-1]=cp
        else:result.extend((cp,cp))
    return result

def main():
    if ud.unidata_version!=VERSION:
        raise SystemExit(f'Expected Unicode {VERSION}; this interpreter has {ud.unidata_version}. Use the pinned builder.')
    decompositions=[];compositions=[];classes=[];letters=[];ignored=[]
    for cp in range(0x110000):
        c=chr(cp);decomposition=ud.decomposition(c)
        if decomposition and not decomposition.startswith('<'):
            parts=[int(x,16) for x in decomposition.split()]
            if len(parts)>2:raise AssertionError('Canonical mapping exceeds two scalars')
            decompositions.extend((cp,parts[0],parts[1] if len(parts)>1 else 0))
            if len(parts)==2 and ud.normalize('NFC',''.join(map(chr,parts)))==c:compositions.append((parts[0],parts[1],cp))
        ccc=ud.combining(c)
        if ccc:
            if classes and classes[-2]+1==cp and classes[-1]==ccc:classes[-2]=cp
            else:classes.extend((cp,cp,ccc))
        category=ud.category(c)
        if category.startswith('L') or category=='Nd':letters.append(cp)
        # Unicode White_Space, not Python's broader str.isspace (which includes
        # U+001C..1F); those controls are independently excluded as category Cc.
        whitespace=cp in (0x20,0x85,0xa0,0x1680,0x2028,0x2029,0x202f,0x205f,0x3000) or 9<=cp<=13 or 0x2000<=cp<=0x200a
        if whitespace or category in ('Cc','Cf'):ignored.append(cp)
    pairs=[]
    for a,b,c in sorted(compositions):pairs.extend((a,b,c))
    arrays={'Decompositions':decompositions,'Compositions':pairs,'CombiningClasses':classes,'LettersAndDigits':ranges(letters),'Ignored':ranges(ignored)}
    maximum=max(len(ud.normalize('NFD',chr(cp))) for cp in range(0x110000) if not 0xd800<=cp<=0xdfff)
    assert maximum==4
    output=['// Generated by tools/generate-job-unicode.py from Unicode '+VERSION+'.',
            '// Unicode data license: assets/definitions/jobs/UNICODE-LICENSE.txt.',
            'namespace AnimalTown.Jobs;','', 'internal static class JobUnicodeTables','{',
            '    internal const string Version="'+VERSION+'";',
            f'    internal const int DataBytes={sum(map(len,arrays.values()))*4};',
            f'    internal const int MaximumCanonicalExpansion={maximum};']
    for name,values in arrays.items():
        output+=['    internal static readonly int[] '+name+'={']
        output+=['        '+','.join(str(n) for n in values[i:i+12])+',' for i in range(0,len(values),12)]
        output+=['    };']
    output+=['}','']
    (ROOT/'shared/AnimalTown.Domain/Jobs/JobUnicodeTables.g.cs').write_text('\n'.join(output))
    print('Cooked Unicode',VERSION,':',sum(map(len,arrays.values()))*4,'immutable table bytes; canonical expansion',maximum)

if __name__=='__main__':main()
